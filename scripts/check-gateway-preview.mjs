import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const out = '.impeccable/review/gateway-preview';
await mkdir(out, { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1586, height: 992 } });
  page.setDefaultTimeout(15000);
  let user = null;
  let campaignLimit = 12;
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(() => sessionStorage.setItem('vivid-realms-entrance-v2', 'seen'));
  const campaigns = Array.from({ length: 12 }, (_, i) => ({ id: i + 1, name: ['Shadows of Remnant', 'The Dragon’s Wake', 'Dust & Dawn'][i % 3] + (i > 2 ? ` ${i}` : ''), description: 'A story shared with your party. Return to the table and continue the adventure.', system: i % 3 === 1 ? 'dnd5e' : 'remnant', role: i % 3 === 1 ? 'dm' : 'player', member_count: 4 }));
  await page.route('**/api/**', async r => {
    const path = new URL(r.request().url()).pathname;
    if (path === '/api/auth/login') { user = { id: 1, display_name: 'Test player' }; return r.fulfill({ json: user }); }
    return r.fulfill({ json: path === '/api/auth/me' ? { user } : path === '/api/auth/dev-users' ? { users: [{id:1,display_name:'Oni',is_dm:1},{id:2,display_name:'Character',is_dm:0},{id:3,display_name:'ONichan',is_dm:0}] } : path === '/api/campaigns' ? { campaigns: campaigns.slice(0, campaignLimit) } : {} });
  });
  await page.goto('http://localhost:5182/login');
  await page.locator('.gateway').waitFor();
  assert.equal(await page.locator('.gateway-library').count(), 0);
  await page.getByRole('checkbox', { name: /Updated theme/ }).check();
  await page.evaluate(() => document.fonts.ready);
  const assertLoginFits = async () => {
    assert.ok(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight + 1), 'Login must not scroll vertically');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Login must not scroll horizontally');
    for (const selector of ['.gateway-submit', '.library-account-switch']) {
      const box = await page.locator(selector).boundingBox();
      const panel = await page.locator('.gateway-access').boundingBox();
      assert.ok(box && panel && box.y >= panel.y && box.y + box.height <= panel.y + panel.height, `${selector} must fit inside account panel`);
      assert.ok(box.y + box.height <= page.viewportSize().height, `${selector} must remain visible in the viewport`);
    }
  };
  for (const viewport of [{width:1920,height:1080},{width:1912,height:960},{width:1366,height:768},{width:1440,height:900},{width:390,height:844},{width:390,height:667},{width:844,height:390},{width:1586,height:992}]) {
    await page.setViewportSize(viewport);
    await page.waitForTimeout(100);
    await assertLoginFits();
    if (viewport.width === 1366) await page.screenshot({path:`${out}/login-laptop.png`});
    if (viewport.width === 1912) await page.screenshot({path:`${out}/login-wide.png`});
  }
  await page.screenshot({ path: `${out}/login-desktop.png`, fullPage: true });
  assert.equal(await page.locator('.gateway-access-inner').evaluate(el => getComputedStyle(el).overflowY), 'visible');
  await page.locator('.gateway-dev-access summary').click();
  await page.getByRole('heading', {name:'Choose a local account'}).waitFor();
  assert.equal(await page.locator('.gateway-form').isVisible(), false);
  await page.screenshot({path:`${out}/local-account-picker.png`});
  await page.locator('.gateway-dev-access summary').click();
  await page.locator('.gateway-form').waitFor();
  await page.getByRole('button', { name: 'Create an account', exact: true }).click();
  await page.getByLabel('Display name').waitFor();
  await assertLoginFits();
  await page.locator('.library-account-switch').getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Forgot password?', exact: true }).click();
  await page.getByRole('button', { name: 'Send recovery link', exact: true }).waitFor();
  await page.getByRole('button', { name: /Back to login/ }).click();
  await page.reload();
  await page.locator('.gateway-library').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${out}/login-mobile.png`, fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.setViewportSize({ width: 1586, height: 992 });
  await page.getByLabel('Email', { exact: true }).fill('test@example.test');
  await page.locator('input[type="password"]').fill('password123');
  await page.locator('.gateway-submit').click();
  await page.locator('.welcome-library').waitFor();
  await page.waitForTimeout(900);
  await page.screenshot({ path: `${out}/welcome.png` });
  await page.locator('.welcome-library').waitFor({ state: 'detached' });
  await page.locator('.campaign-library').waitFor();
  await page.screenshot({ path: `${out}/lobby-desktop.png` });
  assert.equal(await page.locator('.campaign-directory-card').count(), 12);
  await page.getByRole('searchbox').fill('Dragon');
  assert.equal(await page.locator('.campaign-directory-card').count(), 4);
  await page.getByRole('searchbox').fill('');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${out}/lobby-mobile.png` });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.ok(await page.locator('.select-nav').evaluate(el => el.getBoundingClientRect().right <= innerWidth));
  await page.setViewportSize({ width: 1586, height: 992 });
  campaignLimit = 1;
  await page.reload();
  await page.locator('.campaign-directory-card').waitFor();
  assert.equal(await page.locator('.campaign-directory-card').count(), 1);
  assert.ok((await page.locator('.campaign-select-main').boundingBox()).height >= 795);
  await page.screenshot({ path: `${out}/lobby-single-campaign.png` });
  await page.getByRole('button', { name: '+ Create campaign', exact: true }).click();
  await page.getByRole('heading', { name: 'Open a campaign' }).waitFor();
  await page.getByRole('button', { name: 'Close campaign setup' }).click();
  campaignLimit = 0;
  await page.reload();
  await page.getByRole('heading', { name: 'Your first world is waiting.' }).waitFor();
  assert.equal(await page.locator('.campaign-directory-card').count(), 0);
  await page.getByRole('checkbox', { name: /Updated theme/ }).uncheck();
  assert.equal(await page.locator('.campaign-library').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: login fits seven viewport sizes without page scrolling; registration/recovery, campaign states, search, mobile navigation, persistence and reverting work.');
} finally { await browser.close(); }
